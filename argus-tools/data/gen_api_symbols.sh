#!/bin/sh
# Regenerates api_symbols_f7_<major>.<minor>.txt from a firmware tree's targets/f7/api_symbols.csv.
# Usage: sh gen_api_symbols.sh /path/to/Argus_Firmware/targets/f7/api_symbols.csv
# The loader resolves an app's imports against the firmware's exported table (status '+'), so this
# list is what decides whether an app whose API minor is newer than the firmware's can still load.
set -eu
csv=$1
here=$(dirname "$0")
version=$(grep '^Version,' "$csv" | head -n 1 | cut -d, -f3)
out="$here/api_symbols_f7_$version.txt"
{
    echo "# Exported API symbols of the firmware, hardware target f7, API $version."
    echo "# Generated by gen_api_symbols.sh from targets/f7/api_symbols.csv: Function and Variable entries with status '+'."
    echo "version $version"
    grep -E '^(Function|Variable),\+,' "$csv" | cut -d, -f3 | LC_ALL=C sort -u
} > "$out"
echo "$out: $(grep -vc '^#' "$out") lines"
