//! qFlipper's symbolic icons (application/assets/gfx/symbolic and controls/windows, GPL-3.0 with qFlipper), as the
//! pixels they are drawn of: each SVG there is made of whole-pixel rectangles, rasterised once at its own size and
//! written down here. Drawn as one mesh of plain quads (no anti-aliased edges, which would halve a 1 px line) in any
//! colour, so they stay sharp at any scale and take the accent.

use eframe::egui::{epaint::Mesh, pos2, vec2, Color32, Painter, Pos2, Rect, Shape};

pub struct Icon {
    pub w: u8,
    pub h: u8,
    rows: &'static [&'static str],
}

impl Icon {
    /// Draws the icon centred on `c` (rounded to whole pixels), each run of lit pixels in a row as one quad.
    pub fn draw(&self, p: &Painter, c: Pos2, colour: Color32) {
        self.paint(p, c, colour, false);
    }

    /// Draws it turned upside down (QML's `rotation: 180`).
    pub fn draw_flipped(&self, p: &Painter, c: Pos2, colour: Color32) {
        self.paint(p, c, colour, true);
    }

    fn paint(&self, p: &Painter, c: Pos2, colour: Color32, flipped: bool) {
        let origin = pos2((c.x - self.w as f32 / 2.0).round(), (c.y - self.h as f32 / 2.0).round());
        let mut mesh = Mesh::default();
        for (y, row) in self.rows.iter().enumerate() {
            let bytes = row.as_bytes();
            let mut x = 0;
            while x < bytes.len() {
                if bytes[x] != b'#' {
                    x += 1;
                    continue;
                }
                let start = x;
                while x < bytes.len() && bytes[x] == b'#' {
                    x += 1;
                }
                let (left, top) = if flipped { (self.w as usize - x, self.h as usize - 1 - y) } else { (start, y) };
                let r = Rect::from_min_size(origin + vec2(left as f32, top as f32), vec2((x - start) as f32, 1.0));
                mesh.add_colored_rect(r, colour);
            }
        }
        p.add(Shape::mesh(mesh));
    }
}

